"""Generate the mobile schema from the canonical server JSON; --check is a CI gate."""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'backend-api-runtime/resources/property-schema.json'
target = root / 'mobile_app/lib/features/properties/domain/property_schema_definition.g.dart'
raw = source.read_bytes()
definition = json.loads(raw)
expected = '// Generated by scripts/generate_property_schema.py. Do not edit.\n'
expected += '// SHA256: ' + hashlib.sha256(raw).hexdigest() + '\n'
expected += "import 'dart:convert';\n\n"
expected += 'final Map<String, dynamic> propertySchemaDefinition = jsonDecode(r\'\'\''
expected += json.dumps(definition, ensure_ascii=False, separators=(',', ':'))
expected += "''' ) as Map<String, dynamic>;\n"
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != expected:
        raise SystemExit('Property schema is out of date; run the generator.')
    print('Property schema matches canonical definition.')
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(expected)
