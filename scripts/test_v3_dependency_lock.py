import unittest

from verify_v3_dependency_lock import MISSING_PACKAGES, verify


def package(name, version):
    return (
        f"  {name}:\n"
        "    dependency: transitive\n"
        "    description:\n"
        f"      name: {name}\n"
        f"      sha256: {'a' * 64}\n"
        '      url: "https://pub.dev"\n'
        "    source: hosted\n"
        f'    version: "{version}"\n'
    )


class DependencyLockGuardTests(unittest.TestCase):
    def setUp(self):
        header = "# Generated by pub\npackages:\n"
        self.sdks = 'sdks:\n  dart: ">=3.6.0 <4.0.0"\n  flutter: ">=3.27.0"\n'
        self.original = header + package("dio", "5.11.0") + self.sdks
        self.resolved = header + package("dio", "5.11.0")
        self.resolved += "".join(package(name, version) for name, version in MISSING_PACKAGES.items())
        self.resolved += self.sdks

    def test_missing_declared_plugin_completion_passes(self):
        self.assertEqual(verify(self.original, self.resolved), 1)

    def test_changing_original_package_version_fails(self):
        with self.assertRaisesRegex(ValueError, "Original locked packages"):
            verify(self.original, self.resolved.replace('version: "5.11.0"', 'version: "5.11.1"'))

    def test_changing_original_archive_checksum_fails(self):
        changed = self.resolved.replace("a" * 64, "b" * 64, 1)
        with self.assertRaisesRegex(ValueError, "Original locked packages"):
            verify(self.original, changed)

    def test_unexpected_template_dependency_fails(self):
        changed = self.resolved.replace("sdks:\n", package("firebase_auth", "1.0.0") + "sdks:\n")
        with self.assertRaisesRegex(ValueError, "Unexpected added dependency"):
            verify(self.original, changed)

    def test_unpinned_launcher_version_fails(self):
        with self.assertRaisesRegex(ValueError, "Unexpected build-only package version"):
            verify(self.original, self.resolved.replace('version: "6.3.2"', 'version: "6.3.3"'))

    def test_sdk_upgrade_fails(self):
        with self.assertRaisesRegex(ValueError, "SDK constraints"):
            verify(self.original, self.resolved.replace(">=3.27.0", ">=3.35.0"))


if __name__ == "__main__":
    unittest.main()
