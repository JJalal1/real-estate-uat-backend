SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))
SPEC = importlib.util.spec_from_file_location('apk_cleanup_verifier', SCRIPTS / 'verify_apk_cleanup.py')
subject = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(subject)
SOURCE = 'a' * 40


def identity():
    return {'certificate_sha256': subject.CERTIFICATE,
            'approved_for_delivery': True, 'github_secret_storage_verified': True}


def environment():
    return {'GITHUB_ACTIONS': 'true', 'GITHUB_REPOSITORY': 'JJalal1/real-estate-uat-backend',
            'GITHUB_REF': subject.BRANCH, 'GITHUB_EVENT_NAME': 'push', 'GITHUB_SHA': SOURCE,
            'AQER_SIGNING_ENVIRONMENT': 'uat', 'AQER_UAT_SIGNING_CONFIGURED': 'true',
            'AQER_ALLOW_DEBUG_RELEASE_SIGNING': 'false',
            'AQER_UAT_SIGNING_CERT_SHA256': subject.CERTIFICATE, 'ANDROID_HOME': '/sdk'}


def baseline_metadata():
    return {'source_commit': subject.BASELINE_SOURCE, 'package': subject.PACKAGE,
            'version_code': 1817, 'api': subject.API, 'application_name': subject.APP_NAME,
            'signer_certificate_sha256': subject.CERTIFICATE,
            'sha256': subject.BASELINE_SHA256, 'bytes': subject.BASELINE_BYTES,
            'debug_signing_allowed': False, 'approved_for_delivery': True,
            'github_secret_storage_verified': True}


def synthetic_apk(path, version=1817, *, extra=None, omit=None, bad_api=False,
                  changed_native=False, changed_asset=False, unaligned=False):
    entries = subject.EXPECTED_NATIVE | (subject.REMOVED_NATIVE if version == 1817 else set())
    if omit:
        entries = entries - {omit}
    with zipfile.ZipFile(path, 'w') as archive:
        for name in sorted(entries):
            if name.endswith('/libapp.so'):
                payload = (b'wrong origin' if bad_api else subject.API.encode()) + str(version).encode()
            else:
                payload = name.encode() + (b'changed' if changed_native and name.endswith('/libmaplibre.so') else b'')
            method = zipfile.ZIP_DEFLATED if version == 1819 else zipfile.ZIP_STORED
            entry = zipfile.ZipInfo(name)
            entry.compress_type = method
            if method == zipfile.ZIP_STORED and not unaligned:
                padding = (-(archive.fp.tell() + 30 + len(name.encode()))) % 16384
                if padding < 4:
                    padding += 16384
                entry.extra = struct.pack('<HH', 0xd935, padding - 4) + bytes(padding - 4)
            archive.writestr(entry, payload)
        archive.writestr('assets/flutter_assets/assets/photo.png', b'changed' if changed_asset else b'original')
        archive.writestr('assets/flutter_assets/FontManifest.json', b'{"font":"unchanged"}')
        archive.writestr('assets/flutter_assets/fonts/MaterialIcons-Regular.otf', b'original icons')
        archive.writestr(subject.GENERATED_LICENSE, b'generated licenses ' + str(version).encode())
        archive.writestr('classes.dex', b'generated bytecode ' + str(version).encode())
        archive.writestr('assets/dexopt/baseline.prof', b'generated profile ' + str(version).encode())
        if extra:
            archive.writestr(extra, b'unexpected')


class CleanupVerifierGuards(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.elf = mock.patch.object(subject, 'elf')
        self.elf.start()
        self.addCleanup(self.elf.stop)

    def test_explicit_branch_push_and_approved_durable_key_required(self):
        subject.guard(environment(), SOURCE, identity())
        for key, value in [('GITHUB_ACTIONS', 'false'), ('GITHUB_REPOSITORY', 'other/repo'),
                           ('GITHUB_REF', 'refs/heads/main'), ('GITHUB_EVENT_NAME', 'pull_request'),
                           ('GITHUB_SHA', 'b' * 40), ('AQER_SIGNING_ENVIRONMENT', 'production'),
                           ('AQER_UAT_SIGNING_CONFIGURED', 'false'),
                           ('AQER_ALLOW_DEBUG_RELEASE_SIGNING', 'true'),
                           ('AQER_UAT_SIGNING_CERT_SHA256', 'b' * 64)]:
            with self.subTest(key=key), self.assertRaises(ValueError):
                subject.guard({**environment(), key: value}, SOURCE, identity())
        with self.assertRaises(subject.CleanupError):
            subject.guard(environment(), SOURCE, {**identity(), 'certificate_sha256': 'b' * 64})

    def test_public_baseline_is_fixed_and_unknown_fields_are_not_exported(self):
        path = self.root / 'baseline.json'
        raw = {**baseline_metadata(), 'not_for_export': 'SENSITIVE_SENTINEL'}
        path.write_text(json.dumps(raw))
        record = subject.baseline_receipt(path)
        self.assertNotIn('SENSITIVE_SENTINEL', json.dumps(subject.public_identity(record)))
        for field, value in [('source_commit', SOURCE), ('version_code', True), ('bytes', 1),
                             ('sha256', 'a' * 64), ('package', 'wrong'),
                             ('debug_signing_allowed', True), ('github_secret_storage_verified', False)]:
            path.write_text(json.dumps({**raw, field: value}))
            with self.subTest(field=field), self.assertRaises(subject.CleanupError):
                subject.baseline_receipt(path)

    def test_duplicate_baseline_json_keys_fail(self):
        path = self.root / 'baseline.json'
        path.write_text('{"sha256":"a","sha256":"b"}')
        with self.assertRaises(subject.CleanupError):
            subject.baseline_receipt(path)

    def test_input_paths_cannot_escape_workspace_or_follow_symlinks(self):
        path = self.root / 'input.apk'
        path.write_bytes(b'fixture')
        link = self.root / 'link.apk'
        link.symlink_to(path)
        with mock.patch.object(subject, 'ROOT', self.root):
            self.assertEqual(subject.regular_input(path, '.apk'), path)
            for value, suffix in [(link, '.apk'), (self.root / 'missing.apk', '.apk'), (path, '.json')]:
                with self.subTest(value=value), self.assertRaises(subject.CleanupError):
                    subject.regular_input(value, suffix)

    def test_android_package_signer_version_and_sdk_are_verified(self):
        signature = 'Signer #1 certificate SHA-256 digest: ' + subject.CERTIFICATE
        badging = (f"package: name='{subject.PACKAGE}' versionCode='1818'\n"
                   f"sdkVersion:'23'\ntargetSdkVersion:'36'\napplication-label:'{subject.APP_NAME}'")
        with mock.patch.object(subject, 'call', side_effect=[signature, badging, '']) as command:
            subject.verify_android_identity(self.root / 'input.apk', Path('/tools'), 1818)
            self.assertEqual(command.call_count, 3)
        with mock.patch.object(subject, 'call', return_value=signature.replace(subject.CERTIFICATE, 'b' * 64)):
            with self.assertRaises(subject.CleanupError):
                subject.verify_android_identity(self.root / 'input.apk', Path('/tools'), 1818)
        for changed in [badging.replace("versionCode='1818'", "versionCode='1817'"),
                        badging.replace("sdkVersion:'23'", "sdkVersion:'21'"),
                        badging + '\napplication-debuggable']:
            with mock.patch.object(subject, 'call', side_effect=[signature, changed]):
                with self.assertRaises(subject.CleanupError):
                    subject.verify_android_identity(self.root / 'input.apk', Path('/tools'), 1818)

    def test_explicit_manifest_extraction_policy_required(self):
        def manifest(value):
            return '    A: android:extractNativeLibs(0x010104ea)=(type 0x12)' + value + '\n'
        self.assertFalse(subject.extract_native_libs(manifest('0x0')))
        self.assertTrue(subject.extract_native_libs(manifest('0xffffffff')))
        for invalid in ['', manifest('0x1'), manifest('0x0') + manifest('0x0')]:
            with self.assertRaises(subject.CleanupError):
                subject.extract_native_libs(invalid)

    def test_exact_clean_native_set_excludes_orphans_sqlite_and_missing_engine(self):
        path = self.root / 'candidate.apk'
        for extra, omit in [('lib/x86/libmaplibre.so', None),
                            ('lib/arm64-v8a/libsqlite3.so', None),
                            (None, 'lib/arm64-v8a/libflutter.so')]:
            synthetic_apk(path, 1818, extra=extra, omit=omit)
            with self.subTest(extra=extra, omit=omit), self.assertRaises(subject.CleanupError):
                subject.inspect_archive(path, candidate_version=1818)

    def test_native_methods_and_stored_alignment_match_version(self):
        stored, compressed = self.root / 'stored.apk', self.root / 'compressed.apk'
        synthetic_apk(stored, 1818)
        synthetic_apk(compressed, 1819)
        before = subject.inspect_archive(stored, candidate_version=1818)
        after = subject.inspect_archive(compressed, candidate_version=1819)
        self.assertEqual(set(before['native_library_methods'].values()), {zipfile.ZIP_STORED})
        self.assertEqual(set(after['native_library_methods'].values()), {zipfile.ZIP_DEFLATED})
        self.assertTrue(all(before['native_zip_16kb_aligned'].values()))
        for path, version in [(stored, 1819), (compressed, 1818)]:
            with self.assertRaises(subject.CleanupError):
                subject.inspect_archive(path, candidate_version=version)
        synthetic_apk(stored, 1818, unaligned=True)
        with self.assertRaises(subject.CleanupError):
            subject.inspect_archive(stored, candidate_version=1818)

    def test_compiled_api_mismatch_fails(self):
        path = self.root / 'candidate.apk'
        synthetic_apk(path, 1818, bad_api=True)
        with self.assertRaises(subject.CleanupError):
            subject.inspect_archive(path, candidate_version=1818)

    def test_private_signing_file_cannot_enter_exported_apk(self):
        path = self.root / 'candidate.apk'
        synthetic_apk(path, 1818, extra='assets/secret.p12')
        with self.assertRaises(subject.CleanupError):
            subject.inspect_archive(path, candidate_version=1818)

    def test_assets_and_retained_native_hashes_are_pinned_but_aot_dex_may_change(self):
        baseline, candidate = self.root / 'base.apk', self.root / 'candidate.apk'
        synthetic_apk(baseline)
        synthetic_apk(candidate, 1818)
        before = subject.inspect_archive(baseline)
        after = subject.inspect_archive(candidate, candidate_version=1818)
        preserved = subject.compare_baseline(before, after)
        self.assertEqual(len(preserved), 9)
        self.assertNotEqual(before['dex_sha256'], after['dex_sha256'])
        for kwargs in [{'changed_asset': True}, {'changed_native': True}]:
            synthetic_apk(candidate, 1818, **kwargs)
            with self.subTest(kwargs=kwargs), self.assertRaises(subject.CleanupError):
                subject.compare_baseline(before, subject.inspect_archive(candidate, candidate_version=1818))

    def test_protected_runtime_trees_cannot_change(self):
        with mock.patch.object(subject, 'call', side_effect=['c' * 40] * 8 + ['']):
            self.assertEqual(len(subject.source_guards(SOURCE)), 4)
        with mock.patch.object(subject, 'call', side_effect=['c' * 40, 'd' * 40]):
            with self.assertRaises(subject.CleanupError):
                subject.source_guards(SOURCE)

    def test_sequential_version_outputs_do_not_overwrite_baseline_or_each_other(self):
        baseline = self.root / 'baseline.apk'
        meta = self.root / 'baseline.json'
        synthetic_apk(baseline)
        expected_sha, expected_bytes = subject.digest(baseline), baseline.stat().st_size
        candidate = self.root / 'mobile_app/build/app/outputs/flutter-apk/app-uat-release.apk'
        candidate.parent.mkdir(parents=True)
        lock = self.root / 'mobile_app/pubspec.lock'
        lock.write_text('synthetic lock')
        protected = {name: 'c' * 40 for name in subject.PROTECTED_TREES}
        def command(*values):
            if values[:3] == ('git', 'rev-parse', 'HEAD'):
                return SOURCE
            if 'xmltree' in values:
                return (' A: android:extractNativeLibs(0x010104ea)=(type 0x12)' +
                        ('0xffffffff' if current[0] == 1819 else '0x0'))
            return 'c' * 40
        current = [1818]
        with mock.patch.object(subject, 'ROOT', self.root), \
                mock.patch.object(subject, 'BASELINE_SHA256', expected_sha), \
                mock.patch.object(subject, 'BASELINE_BYTES', expected_bytes), \
                mock.patch.object(subject, 'load_public_identity', return_value=identity()), \
                mock.patch.object(subject, 'source_guards', return_value=protected), \
                mock.patch.object(subject, 'android_tools', return_value=Path('/tools')), \
                mock.patch.object(subject, 'verify_android_identity'), \
                mock.patch.object(subject, 'call', side_effect=command), \
                mock.patch.dict(os.environ, environment(), clear=True), \
                contextlib.redirect_stdout(io.StringIO()):
            meta.write_text(json.dumps(baseline_metadata()))
            for version in (1818, 1819):
                current[0] = version
                synthetic_apk(candidate, version)
                subject.main(['--version', str(version), '--baseline-apk', str(baseline),
                              '--baseline-receipt', str(meta)])
                output = self.root / 'mobile_app/apk-cleanup-proof' / str(version)
                self.assertEqual({p.name for p in output.iterdir()}, {
                    f'AQER-UAT-{version}-Clean.apk', 'APK_VERIFICATION.json'})
                receipt = json.loads((output / 'APK_VERIFICATION.json').read_text())
                self.assertEqual(receipt['version_code'], version)
                self.assertEqual(receipt['sha256'], subject.digest(output / f'AQER-UAT-{version}-Clean.apk'))
                self.assertEqual(receipt['extract_native_libs'], version == 1819)
                self.assertEqual(len(receipt['native_library_sha256']), 12)
                self.assertFalse(receipt['physical_phone_acceptance'])
            self.assertTrue((self.root / 'mobile_app/apk-cleanup-proof/1818/APK_VERIFICATION.json').is_file())
            self.assertEqual(subject.digest(baseline), expected_sha)


