  static List<String> get governorates =>
      districtsByGovernorate.keys.toList(growable: false);

  static String canonicalGovernorate(String value) {
    final trimmed = value.trim();
    return _governorateAliases[trimmed] ?? trimmed;
  }

  static List<String> districtsFor(String governorate) =>
      districtsByGovernorate[canonicalGovernorate(governorate)] ??
      const <String>[];

  static int get totalDistrictCount => districtsByGovernorate.values
      .fold<int>(0, (total, districts) => total + districts.length);
}
